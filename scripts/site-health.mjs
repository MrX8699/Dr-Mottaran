const historyPath = path.join(outDir, "history.json")
let history = []
try {
  history = JSON.parse(await readFile(historyPath, "utf8"))
} catch {}
history = history.filter((h) => h.date !== day)
history.push({
  date: day,
  visitors24h: period("Last 24 hours")?.visitors ?? null,
  visitors7d: period("Last 7 days")?.visitors ?? null,
  visitors30d: period("Last 30 days")?.visitors ?? null,
  views30d: period("Last 30 days")?.views ?? null,
  googleClicks28d: google?.clicks ?? null,
  googleImpressions28d: google?.impressions ?? null,
  googlePosition: google?.position ?? null,
  googleIndexed: google?.indexed ?? null,
  healthOk: counts.ok,
  healthWarn: counts.warn,
  healthFail: counts.fail,
})
history.sort((a, b) => a.date.localeCompare(b.date))
history = history.slice(-400)

const ranAt = startedAt.toISOString()
const code = await readFile(scriptPath, "utf8")
const statsMeta = [{ label: "Collected", value: stats?.collectedAt ?? "never" }, { label: "Collected by", value: "Daily Claude task, from the signed-in Claude browser" }]
const out = {
  generatedAt: ranAt,
  health: {
    rows,
    meta: [
      { label: "Checked", value: ranAt },
      { label: "Result", value: `${counts.ok} ok, ${counts.warn} warnings, ${counts.fail} failing` },
      { label: "site-health.mjs", value: code, type: "code", lang: "javascript" },
    ],
  },
  visits: { rows: umami?.periods ?? [], meta: [{ label: "Source", value: "Umami Cloud, cloud.umami.is" }, ...statsMeta] },
  pages: { rows: (umami?.pages ?? []).map((p) => ({ path: p.path, visitors: p.visitors })), meta: [{ label: "Period", value: "Last 30 days" }, ...statsMeta] },
  referrers: { rows: (umami?.referrers ?? []).map((r) => ({ source: r.source, visitors: r.visitors })), meta: [{ label: "Period", value: "Last 30 days" }, ...statsMeta] },
  countries: { rows: (umami?.countries ?? []).map((c) => ({ country: c.country, visitors: c.visitors })), meta: [{ label: "Period", value: "Last 30 days" }, ...statsMeta] },
  search: {
    rows: [
      google && { engine: "Google", period: google.period, clicks: google.clicks, impressions: google.impressions, ctr: google.ctr, position: google.position, indexed: google.indexed ?? null, sitemap: google.sitemap ?? "" },
      bing && { engine: "Bing", period: bing.period, clicks: bing.clicks, impressions: bing.impressions, ctr: bing.ctr ?? "", position: bing.position ?? null, indexed: bing.indexed ?? null, sitemap: bing.sitemap ?? "" },
    ].filter(Boolean),
    meta: [{ label: "Source", value: "Google Search Console and Bing Webmaster Tools" }, ...statsMeta],
  },
  queries: { rows: (google?.queries ?? []).map((q) => ({ query: q.query, clicks: q.clicks, impressions: q.impressions })), meta: [{ label: "Period", value: google?.period ?? "Last 28 days" }, ...statsMeta] },
  history: { rows: history, meta: [{ label: "Source", value: "One row per daily run of site-health.mjs" }] },
}

await mkdir(outDir, { recursive: true })
await writeFile(historyPath, JSON.stringify(history, null, 2))
await writeFile(path.join(outDir, "site-health.json"), JSON.stringify(out))
console.log(`site-health: ${counts.ok} ok, ${counts.warn} warn, ${counts.fail} fail → monitoring/site-health.json`)
for (const r of rows.filter((r) => r.status !== "ok")) console.log(`  [${r.status}] ${r.area} / ${r.check}: ${r.detail}`)
