#!/usr/bin/env node
// Site health check for drlucamottaran.it ("npm run health").
//
// Checks the live site, DNS, HTTPS certificate, domain, releases, CI and
// deploy runs, Dependabot pull requests and npm audit, then merges in the
// visit and search numbers collected from Umami, Search Console and Bing
// (monitoring/web-stats.json, written by the daily Claude task). It writes:
//
//   monitoring/site-health.json   everything the "Mottaran Site Health"
//                                 dashboard shows, one key per dataset
//   monitoring/history.json       one row per day, kept between runs
//
// monitoring/ is gitignored. The script needs Node 22, no packages, and never
// touches .next, so it is safe to run while `npm run dev` is running.
//
// monitoring/web-stats.json (optional; missing or old numbers show as a
// warning on the dashboard):
// {
//   "collectedAt": "2026-11-24T08:00:00+01:00",
//   "umami": { "periods": [{ "period": "Last 24 hours", "visitors": 0, "visits": 0, "views": 0,
//              "bounceRate": "0%", "visitDuration": "0s" }, ...7 days, ...30 days],
//              "pages": [{ "path": "/", "visitors": 1 }], "referrers": [{ "source": "google.com", "visitors": 1 }],
//              "countries": [{ "country": "Italy", "visitors": 1 }], "browsers": [{ "browser": "Chrome", "visitors": 1 }] }
//            or { "error": "why it could not be read" },
//   "google": { "period": "Last 28 days", "clicks": 6, "impressions": 127, "ctr": "4.7%", "position": 5.6,
//               "indexed": 18, "notIndexed": 4, "sitemap": "Riuscito",
//               "queries": [{ "query": "chinesiologo", "clicks": 0, "impressions": 8 }] } or { "error": "..." },
//   "bing": { "period": "Last 30 days", "clicks": 0, "impressions": 0, "indexed": 0, "sitemap": "Success" }
//           or { "error": "..." }
// }

