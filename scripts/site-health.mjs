const SITE = `https://${DOMAIN}`
const REPO = "MrX8699/Dr-Mottaran"
const GITHUB_PAGES_IPS = ["185.199.108.153", "185.199.109.153", "185.199.110.153", "185.199.111.153"]
const PAGES_HOST = "mrx8699.github.io"
const GOOGLE_TXT = "google-site-verification=1Z9EiTb8r-h7HSdhfXMdI_0qCRcd8evKgniP4VknwWs"

const scriptPath = fileURLToPath(import.meta.url)
const repoRoot = path.resolve(path.dirname(scriptPath), "..")
const outDir = path.join(repoRoot, "monitoring")

const rows = []
function add(area, check, status, detail, fix = "") {
  rows.push({ order: rows.length + 1, area, check, status, detail, fix })
}

async function get(url, opts = {}) {
  return fetch(url, { signal: AbortSignal.timeout(20000), headers: { "User-Agent": "site-health-check" }, ...opts })
}

async function github(endpoint) {
  const res = await get(`https://api.github.com/repos/${REPO}${endpoint}`, {
    headers: { "User-Agent": "site-health-check", Accept: "application/vnd.github+json" },
  })
  if (!res.ok) throw new Error(`GitHub API ${res.status} for ${endpoint}`)
  return res.json()
}

async function guard(area, check, fn, fix) {
  try {
    await fn()
  } catch (err) {
    add(area, check, "warn", `Could not check: ${err.message}`, fix ?? "Usually temporary (network or GitHub API limit). It is checked again on the next run.")
  }
}

// ---------- Live site ----------
async function checkPages() {
  const res = await get(`${SITE}/sitemap.xml`)
  if (!res.ok) {
    add("Live site", "Sitemap", "fail", `sitemap.xml answered ${res.status}`, "The sitemap is generated by the build. Check the last deploy below and release again with \"codia\".")
    return
  }
  const xml = await res.text()
  const urls = [...xml.matchAll(/<loc>([^<]+)<\/loc>/g)].map((m) => m[1])
  add("Live site", "Sitemap", "ok", `${urls.length} pages listed`)

  const broken = []
  const slow = []
  for (let i = 0; i < urls.length; i += 6) {
    await Promise.all(
      urls.slice(i, i + 6).map(async (url) => {
        const t0 = Date.now()
        try {
          const r = await get(url)
          await r.arrayBuffer()
          if (r.status !== 200) broken.push(`${url.replace(SITE, "")} (${r.status})`)
          else if (Date.now() - t0 > 4000) slow.push(url.replace(SITE, ""))
        } catch (err) {
          broken.push(`${url.replace(SITE, "")} (${err.name === "TimeoutError" ? "timeout" : err.message})`)
        }
      }),
    )
  }
  if (broken.length) {
    add("Live site", "All pages respond", "fail", `${broken.length} of ${urls.length} failing: ${broken.join(", ")}`,
      "Open the last deploy run (below). If it failed, fix the error and release again with \"codia\". If GitHub Pages itself is down, check githubstatus.com and wait.")
  } else if (slow.length) {
    add("Live site", "All pages respond", "warn", `All ${urls.length} respond, slow (over 4 s): ${slow.join(", ")}`, "Usually a temporary GitHub Pages slowdown. If it repeats for days, ask Claude to look at image sizes on those pages.")
  } else {
    add("Live site", "All pages respond", "ok", `All ${urls.length} pages answer 200`)
  }

  const robots = await get(`${SITE}/robots.txt`).then((r) => (r.ok ? r.text() : ""))
  if (/Sitemap:\s*https:\/\/drlucamottaran\.it\/sitemap\.xml/i.test(robots) && !/Disallow:\s*\/\s*$/im.test(robots)) {
    add("Live site", "robots.txt", "ok", "Allows search engines and points to the sitemap")
  } else {
    add("Live site", "robots.txt", "fail", "robots.txt is missing, blocks search engines or does not name the sitemap", "It comes from src/app/robots.ts. Ask Claude to check it, then release.")
  }
}

async function checkRedirects() {
  const http = await get(`http://${DOMAIN}/`, { redirect: "manual" })
  const httpTo = http.headers.get("location") ?? ""
  if ([301, 308].includes(http.status) && httpTo.startsWith("https://")) add("Live site", "HTTP to HTTPS", "ok", `http:// redirects (${http.status}) to https://`)
  else add("Live site", "HTTP to HTTPS", "fail", `http:// answered ${http.status} ${httpTo}`, "GitHub repository → Settings → Pages: turn on Enforce HTTPS.")

  const www = await get(`https://www.${DOMAIN}/`, { redirect: "manual" })
  const wwwTo = www.headers.get("location") ?? ""
  if ([301, 308].includes(www.status) && wwwTo.startsWith(`https://${DOMAIN}`)) add("Live site", "www redirect", "ok", `www.${DOMAIN} redirects to ${DOMAIN}`)
  else add("Live site", "www redirect", "warn", `www answered ${www.status} ${wwwTo}`, `Aruba DNS needs CNAME www → ${PAGES_HOST}, and GitHub Settings → Pages custom domain must be ${DOMAIN}.`)
}

async function checkAnalytics() {
  const siteTs = await readFile(path.join(repoRoot, "src/lib/site.ts"), "utf8")
  const id = siteTs.match(/websiteId:\s*"([^"]*)"/)?.[1] ?? ""
  const html = await get(`${SITE}/`).then((r) => r.text())
  if (!id) add("Live site", "Visit counter (Umami)", "warn", "No Umami website ID in src/lib/site.ts, so visits are not counted", "Set analytics.websiteId in src/lib/site.ts and release.")
  else if (html.includes("cloud.umami.is/script.js") && html.includes(id)) add("Live site", "Visit counter (Umami)", "ok", "Umami script is on the live pages")
  else add("Live site", "Visit counter (Umami)", "fail", "The live home page does not load the Umami script", "The site code has the ID but the live site does not: release main with \"codia\". If it is already released, ask Claude to check src/components/Analytics.tsx.")
}

// ---------- Certificate, domain, DNS ----------
function certExpiry() {
  return new Promise((resolve, reject) => {
    const socket = tlsConnect({ host: DOMAIN, port: 443, servername: DOMAIN, timeout: 15000 }, () => {
      const cert = socket.getPeerCertificate()
      socket.end()
      resolve({ validTo: new Date(cert.valid_to), issuer: cert.issuer?.O ?? cert.issuer?.CN ?? "" })
    })
    socket.on("error", reject)
    socket.on("timeout", () => socket.destroy(new Error("timeout")))
  })
}

async function checkCert() {
  const { validTo, issuer } = await certExpiry()
  const days = Math.floor((validTo - Date.now()) / 864e5)
  const detail = `${issuer} certificate valid until ${validTo.toISOString().slice(0, 10)} (${days} days)`
  const fix = "GitHub renews it on its own while DNS points at GitHub Pages. If it keeps falling, check the DNS rows here, then in GitHub Settings → Pages remove and re-add the custom domain to request a new certificate."
  add("Domain and DNS", "HTTPS certificate", days < 7 ? "fail" : days < 20 ? "warn" : "ok", detail, days < 20 ? fix : "")
}

function whois(domain) {
  return new Promise((resolve, reject) => {
    let data = ""
    const s = netConnect(43, "whois.nic.it", () => s.write(`${domain}\r\n`))
    s.setTimeout(15000, () => s.destroy(new Error("timeout")))
    s.on("data", (c) => (data += c))
    s.on("end", () => resolve(data))
    s.on("error", reject)
  })
}

async function checkDomain() {
  const text = await whois(DOMAIN)
  const expire = text.match(/Expire Date:\s*(\S+)/)?.[1]
  const status = text.match(/Status:\s*(.+)/)?.[1]?.trim()
  if (!expire) throw new Error("registry did not return an expiry date")
  const days = Math.floor((new Date(expire) - Date.now()) / 864e5)
  const fix = "Renew drlucamottaran.it in the Aruba panel (admin.aruba.it) before the date, and turn on automatic renewal there."
  add("Domain and DNS", "Domain registration", status !== "ok" || days < 14 ? "fail" : days < 60 ? "warn" : "ok",
    `Registered at Aruba until ${expire} (${days} days), registry status "${status}"`, days < 60 || status !== "ok" ? fix : "")
}

async function checkDns() {
  const resolver = new dnsPromises.Resolver()
  resolver.setServers(["8.8.8.8", "1.1.1.1"])

  const a = (await resolver.resolve4(DOMAIN)).sort()
  const missing = GITHUB_PAGES_IPS.filter((ip) => !a.includes(ip))
  const extra = a.filter((ip) => !GITHUB_PAGES_IPS.includes(ip))
  if (!missing.length && !extra.length) add("Domain and DNS", "Site address (A records)", "ok", "Points at GitHub Pages (4 addresses)")
  else add("Domain and DNS", "Site address (A records)", "fail", `Missing: ${missing.join(", ") || "none"}. Unexpected: ${extra.join(", ") || "none"}`,
    `Aruba DNS panel (dns-panel.aruba.it): the A records for @ must be exactly ${GITHUB_PAGES_IPS.join(", ")}.`)

  const cname = await resolver.resolveCname(`www.${DOMAIN}`).catch(() => [])
  if (cname.includes(PAGES_HOST)) add("Domain and DNS", "www record", "ok", `www points at ${PAGES_HOST}`)
  else add("Domain and DNS", "www record", "warn", `www points at ${cname.join(", ") || "nothing"}`, `Aruba DNS panel: CNAME www → ${PAGES_HOST}.`)

  const txt = (await resolver.resolveTxt(DOMAIN)).map((parts) => parts.join(""))
  if (txt.includes(GOOGLE_TXT)) add("Domain and DNS", "Search Console verification", "ok", "Google verification record present")
  else add("Domain and DNS", "Search Console verification", "fail", "The google-site-verification TXT record is missing",
    `Aruba DNS panel: add TXT, host @, value ${GOOGLE_TXT}. Without it Search Console stops being verified (and Bing, which was imported from it).`)
}

// ---------- Releases, CI, updates ----------
function semverKey(tag) {
  return tag.slice(1).split(".").map(Number)
}

async function checkReleases() {
  const tags = (await github("/tags?per_page=100")).map((t) => t.name).filter((n) => /^v\d+\.\d+\.\d+$/.test(n))
  tags.sort((x, y) => {
    const [a, b] = [semverKey(x), semverKey(y)]
    return b[0] - a[0] || b[1] - a[1] || b[2] - a[2]
  })
  const latest = tags[0]
  if (!latest) {
    add("Releases and code", "Live version", "warn", "No version tag yet", "Say \"codia\" in Claude Code to make the first release.")
    return
  }
  const cmp = await github(`/compare/${latest}...main`)
  if (cmp.ahead_by === 0) add("Releases and code", "Live version", "ok", `${latest} is live and matches main`)
  else add("Releases and code", "Live version", "warn",
    `${latest} is live; ${cmp.ahead_by} change(s) on main are not live yet: ${cmp.commits.slice(-5).map((c) => c.commit.message.split("\n")[0]).join(" · ")}`,
    "When they look right locally and the CI check below is green, say \"codia\" in Claude Code to release them.")
}

async function checkWorkflow(file, label, failFix, filter) {
  const data = await github(`/actions/workflows/${file}/runs?per_page=1${filter}`)
  const run = data.workflow_runs?.[0]
  if (!run) {
    add("Releases and code", label, "warn", "No runs yet")
    return
  }
  const when = run.created_at.slice(0, 10)
  const ref = run.head_branch
  if (run.status !== "completed") add("Releases and code", label, "ok", `Running now (${ref}, started ${when})`)
  else if (run.conclusion === "success") add("Releases and code", label, "ok", `Passed on ${ref} (${when})`)
  else add("Releases and code", label, "fail", `${run.conclusion} on ${ref} (${when}): ${run.html_url}`, failFix)
}

async function checkPullRequests() {
  const prs = await github("/pulls?state=open&per_page=50")
  const bot = prs.filter((p) => p.user?.login === "dependabot[bot]")
  const other = prs.length - bot.length
  if (!prs.length) add("Releases and code", "Update pull requests", "ok", "None waiting")
  else add("Releases and code", "Update pull requests", "warn",
    `${bot.length} Dependabot and ${other} other open: ${prs.map((p) => `#${p.number} ${p.title}`).join(" · ")}`,
    "Ask Claude to review and merge them when their CI is green (\"merge the Dependabot pull requests\"), then \"codia\" to release.")
}

function checkAudit() {
  const r = spawnSync("npm", ["audit", "--json"], { cwd: repoRoot, encoding: "utf8", shell: true, timeout: 120000 })
  const json = JSON.parse(r.stdout || "{}")
  const v = json.metadata?.vulnerabilities
  if (!v) throw new Error(json.error?.summary ?? "npm audit returned no summary")
  const serious = (v.high ?? 0) + (v.critical ?? 0)
  const minor = (v.moderate ?? 0) + (v.low ?? 0)
  const detail = `${v.critical ?? 0} critical, ${v.high ?? 0} high, ${v.moderate ?? 0} moderate, ${v.low ?? 0} low`
  const fix = "Ask Claude to update the dependencies in a separate worktree (README, \"Dependencies\"), then \"esteban\" and \"codia\". The live site is static, so most build-tool advisories do not affect visitors."
  add("Releases and code", "Dependency security (npm audit)", serious ? "fail" : minor ? "warn" : "ok", serious || minor ? detail : "No known vulnerabilities", serious || minor ? fix : "")
}

// ---------- Visits and search (collected in the browser) ----------
async function readWebStats() {
  try {
    return JSON.parse(await readFile(path.join(outDir, "web-stats.json"), "utf8"))
  } catch {
    return null
  }
}

// "24/11/2026, 08:00" in Italian time, whatever the computer's time zone.
function romeTime(iso) {
  return new Date(iso).toLocaleString("it-IT", { timeZone: "Europe/Rome", day: "2-digit", month: "2-digit", year: "numeric", hour: "2-digit", minute: "2-digit" })
}

function checkWebStats(stats) {
  const signIn = (service, where) => `Ask Claude to refresh the dashboard. If it fails again, sign in to ${service} in the Claude app's browser (${where}).`
  if (!stats) {
    add("Visits and search", "Numbers collected", "warn", "No visit or search numbers collected yet", "They are collected by the daily Claude task. Ask Claude to refresh the dashboard.")
    return
  }
  const age = (Date.now() - new Date(stats.collectedAt)) / 36e5
  if (age > 36) add("Visits and search", "Numbers collected", "warn", `Last collected ${romeTime(stats.collectedAt)}, ${Math.round(age)} hours ago`,
    "The daily task did not run (computer off or Claude app closed). It catches up on the next run, or ask Claude to refresh the dashboard.")
  else add("Visits and search", "Numbers collected", "ok", `Collected ${romeTime(stats.collectedAt)}`)
  const sources = [["umami", "Umami visits", "Umami", "cloud.umami.is"], ["google", "Google Search Console", "Search Console", "search.google.com/search-console"], ["bing", "Bing Webmaster Tools", "Bing Webmaster Tools", "bing.com/webmasters"]]
  for (const [key, label, service, where] of sources) {
    const s = stats[key]
    if (!s) add("Visits and search", label, "warn", "Not collected", signIn(service, where))
    else if (s.error) add("Visits and search", label, "warn", `Could not be read: ${s.error}`, signIn(service, where))
    else add("Visits and search", label, "ok", "Read")
  }
  const g = stats.google
  if (g && !g.error && typeof g.notIndexed === "number" && g.notIndexed > 0) {
    add("Visits and search", "Pages in Google", "warn", `${g.indexed} indexed, ${g.notIndexed} not indexed`,
      "Normal for new pages for a few weeks. In Search Console open Indicizzazione → Pagine to see why, and request indexing for important pages in Controllo URL.")
  } else if (g && !g.error && typeof g.indexed === "number") {
    add("Visits and search", "Pages in Google", "ok", `${g.indexed} indexed`)
  }
}

